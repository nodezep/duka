const insertAtBlock = (blockLang) => {
  const marker = `${blockLang}: {`;
  const endMarker = "  },";
  const startIdx = content.indexOf(marker);
  if (startIdx === -1) throw new Error("Could not find " + marker);
  const endIdx = content.indexOf(endMarker, startIdx);
  if (endIdx === -1) throw new Error("Could not find end of " + marker);
  
  // The insertion string
  const insertions = [];
  for (const [key, value] of Object.entries(newTranslations[blockLang])) {
    insertions.push(`    "${key}": "${value}"`);
  }
  
  const toInsert = ",\n" + insertions.join(",\n");
  
  // Find the exact last newline before endIdx
  const lastNewlineIdx = content.lastIndexOf("\n", endIdx - 1);
  content = content.slice(0, lastNewlineIdx) + toInsert + content.slice(lastNewlineIdx);
};

insertAtBlock('es');
insertAtBlock('en');

